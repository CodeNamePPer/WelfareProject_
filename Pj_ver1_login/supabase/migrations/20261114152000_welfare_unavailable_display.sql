-- การแสดงสวัสดิการที่ใช้ไม่ได้ (รีดีไซน์ HR / ดีไซน์ HH3 "การแสดงสวัสดิการที่ใช้ไม่ได้")
--
-- !! ยังไม่ได้ apply รอเจ้าของระบบอนุมัติ !!
--
-- หัวหน้า HR กำหนดรายสวัสดิการว่า เมื่อพนักงานใช้ไม่ได้ (ปิดรับคำขอ ไม่มีวงเงินปีนี้ หรือไม่มีสิทธิ์)
-- หน้าสิทธิ์สวัสดิการของพนักงานจะ "แสดงเป็นการ์ดสีเทา" หรือ "ซ่อน"
--
-- เก็บเป็นคอลัมน์ของ welfare_benefit (ไม่ใช้ system_setting) เพราะดีไซน์ตั้งค่าแยกรายสวัสดิการ
-- ค่าเริ่มต้น faded = แสดงเป็นสีเทา ตรงกับที่หน้าผู้ส่งคำขอแสดงอยู่ตอนนี้ จึงไม่เปลี่ยนสิ่งที่พนักงานเห็นจนกว่าหัวหน้า HR จะตั้งค่า
-- การเปลี่ยนค่าบันทึกใน audit_logs โดยแอป (ดีไซน์: "การเปลี่ยนแปลงบันทึกใน Log และมีผลทันที")
--
-- ยังไม่รวม: หน้าผู้ส่งคำขอ (/employee/welfare) ต้องอ่านคอลัมน์นี้เพื่อซ่อนการ์ด เป็นงานของหน้า Role อื่น
-- =============================================================================

create type public.welfare_unavailable_display as enum ('faded', 'hidden');
comment on type public.welfare_unavailable_display is 'faded=แสดงเป็นการ์ดสีเทา ยื่นคำขอไม่ได้, hidden=ซ่อนจากพนักงาน';

alter table public.welfare_benefit
  add column unavailable_display public.welfare_unavailable_display not null default 'faded';
comment on column public.welfare_benefit.unavailable_display is 'เมื่อพนักงานใช้สวัสดิการนี้ไม่ได้ (ปิดรับ ไม่มีวงเงิน หรือไม่มีสิทธิ์) ให้แสดงเป็นสีเทาหรือซ่อน กำหนดโดยหัวหน้า HR';

